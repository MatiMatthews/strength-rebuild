test('personal setup resumes a separate draft and only activates on confirmation', async ({ page, context }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Crear mi plan', exact: true }).click();
  await page.getByRole('radio', { name: 'Fuerza', exact: true }).click();
  await page.getByRole('radio', { name: 'Entreno con regularidad', exact: true }).click();
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(page.getByText('Tus tres días', { exact: true })).toBeVisible();
  await expect(page.getByText('Borrador local · sin activar', { exact: true })).toBeVisible();
  const draft = await readPersistence(page, info);
  expect(draft.cycles).toHaveLength(0);
  expect(draft.settings.find(row => row.key === 'training-settings')).toBeUndefined();
  await page.close();
  const app = await context.newPage(); await app.goto('/');
  await app.getByRole('button', { name: 'Crear mi plan', exact: true }).click();
  await expect(app.getByText('Tus tres días', { exact: true })).toBeVisible();
  await app.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(app.getByText('Tu gimnasio', { exact: true })).toBeVisible();
  await app.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(app.getByText('Tus referencias', { exact: true })).toBeVisible();
  await app.getByRole('button', { name: 'Ver mi plan', exact: true }).click();
  await expect(app.getByText('Tu plan está listo', { exact: true })).toBeVisible();
  await expect(app.getByText('Borrador local · sin activar', { exact: true })).toBeVisible();
  const preview = await readPersistence(app, info);
  expect(preview.cycles).toHaveLength(0);
  await app.getByRole('button', { name: 'Guardar y salir', exact: true }).click();
  await app.getByRole('button', { name: 'Crear mi plan', exact: true }).click();
  await expect(app.getByText('Tu plan está listo', { exact: true })).toBeVisible();
  await app.getByRole('button', { name: 'Activar mi plan', exact: true }).click();
  await expect(app.getByTestId('cycle-progress-band')).toBeVisible();
  const activated = await readPersistence(app, info);
  expect(activated.cycles.filter(row => row.status === 'ACTIVE')).toHaveLength(1);
  expect(activated.cycles[0]?.kind).toBe('strength');
  expect(activated.templates).toHaveLength(1);
  expect(JSON.stringify(activated.sessionSnapshots)).not.toContain('calculatedLoad');
  await app.reload();
  await expect(app.getByTestId('cycle-progress-band')).toBeVisible();
  expect(await readPersistence(app, info)).toEqual(activated);
  await app.screenshot({ path: info.outputPath('first-personal-plan.png') });
});

