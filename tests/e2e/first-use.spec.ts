test('a conflicting draft write has deliberate cancel and reload recovery', async ({ page }, info) => {
  await page.addInitScript(() => {
    const post = Worker.prototype.postMessage;
    Worker.prototype.postMessage = function(message, transfer) {
      const state = window as unknown as { conflictDraft?: boolean };
      if (state.conflictDraft && message.type === 'prepare' && String(message.data?.source).includes('UPDATE app_setting SET value_json') && String(message.data?.source).includes('NOT EXISTS')) {
        delete state.conflictDraft;
        message.data.source = message.data.source.replace('WHERE key = ?', 'WHERE 0 AND key = ?');
      }
      post.call(this, message, Array.isArray(transfer) ? { transfer } : transfer);
    };
  });
  await page.goto('/setup');
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(page.getByText('Tus tres días', { exact: true })).toBeVisible();
  await expect(page.getByText('Borrador local · sin activar', { exact: true })).toBeVisible();
  const saved = await readPersistence(page, info);
  await page.evaluate(() => { (window as unknown as { conflictDraft: boolean }).conflictDraft = true; });
  await page.getByRole('checkbox', { name: 'Lunes', exact: true }).click();
  await expect(page.getByText(/La configuración o el plan cambió/)).toBeVisible();
  expect(await readPersistence(page, info)).toEqual(saved);
  await page.getByRole('button', { name: 'Recargar borrador guardado', exact: true }).click();
  await page.getByRole('button', { name: 'Conservar mis cambios', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Lunes', exact: true })).toHaveAttribute('aria-checked', 'false');
  await page.getByRole('button', { name: 'Recargar borrador guardado', exact: true }).click();
  await page.getByRole('button', { name: 'Confirmar recarga', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Lunes', exact: true })).toHaveAttribute('aria-checked', 'true');
  await page.getByRole('checkbox', { name: 'Lunes', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Martes', exact: true }).click();
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(page.getByText('Tu gimnasio', { exact: true })).toBeVisible();
});
